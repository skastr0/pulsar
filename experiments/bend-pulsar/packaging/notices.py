#!/usr/bin/env python3
"""THIRD_PARTY_NOTICES for the shipped binaries (#710).

    python3 packaging/notices.py [--target <triple>]... [-o FILE] [--check FILE]

Lists every crate linked into the `pulsar` CLI (normal dependencies, which
includes proc-macro crates since their output is compiled in; build-only
dependencies are left out), with its licence expression and the licence and
notice files it ships. Some crates are published without their licence files
(the oxc crates, pg_query) or vendor C sources whose notices are not in the
crate (pg_query vendors libpg_query, PostgreSQL source, protobuf-c and xxhash):
their texts are kept in packaging/notices/ from the upstream repositories and
attached by SUPPLEMENT below. A shipped crate with no notice text at all fails
the run. Then the engine binary's components: the Bend runtime that the emitted
C contains, and musl for the static Linux builds.

Input: `cargo metadata` of cli/ (run from anywhere; needs the registry fetched).
`--check FILE` regenerates and exits 1 when FILE differs, for the release step.
Output is deterministic: crates sorted by name and version, files by path.
"""
import argparse
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CLI = os.path.join(os.path.dirname(HERE), "cli")
LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE)([-._].*)?$", re.I)
# Directories inside a crate that hold vendored third-party sources whose own
# licence files must travel with the binary. Walked to this depth.
VENDOR_DEPTH = 3
# Crate name (regex, full match) -> notice files in packaging/notices/, from upstream.
SUPPLEMENT = [
    (r"oxc_(allocator|ast|ast_macros|ast_visit|data_structures|diagnostics|ecmascript|estree|parser|regular_expression|semantic|span|str|syntax)", ["oxc.LICENSE"]),
    (r"oxc_resolver", ["oxc-resolver.LICENSE"]),
    (r"oxc_index", ["oxc-index.LICENSE-MIT"]),
    (r"fast-glob", ["fast-glob.LICENSE"]),
    (r"nodejs-built-in-modules", ["nodejs-built-in-modules.LICENSE"]),
    (r"pg_query", ["pg_query.LICENSE", "libpg_query.LICENSE", "postgresql.COPYRIGHT", "protobuf-c.LICENSE", "xxhash.LICENSE"]),
]
SKIP_DIRS = {"tests", "test", "benches", "examples", "target", ".git", "fuzz", "docs"}


def metadata(targets):
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", os.path.join(CLI, "Cargo.toml")]
    for t in targets:
        cmd += ["--filter-platform", t]
    return json.loads(subprocess.run(cmd, check=True, capture_output=True, text=True).stdout)


def shipped(meta):
    """Package ids reachable from the root through normal or proc-macro edges."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for d in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    seen.discard(root)
    return seen


def licence_files(pkg):
    root = os.path.dirname(pkg["manifest_path"])
    out = []
    if pkg.get("license_file"):
        out.append(os.path.normpath(os.path.join(root, pkg["license_file"])))
    for dirpath, dirs, files in os.walk(root):
        depth = os.path.relpath(dirpath, root).count(os.sep) + (0 if dirpath == root else 1)
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and depth < VENDOR_DEPTH)
        for f in sorted(files):
            if LICENCE_FILE.match(f):
                out.append(os.path.join(dirpath, f))
    seen, uniq = set(), []
    for p in out:
        if p not in seen and os.path.isfile(p):
            seen.add(p)
            uniq.append(p)
    return root, uniq


def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read().replace("\r\n", "\n").rstrip() + "\n"


def render(meta, targets):
    pkgs = {p["id"]: p for p in meta["packages"]}
    ids = shipped(meta)
    rows = sorted((pkgs[i] for i in ids), key=lambda p: (p["name"], p["version"]))
    out = [
        "THIRD-PARTY NOTICES for Pulsar",
        "",
        "Pulsar (the `pulsar` CLI and the `pulsar-engine` binary) includes the third-party",
        "components below, under their own licences. This file is generated by",
        "experiments/bend-pulsar/packaging/notices.py from cargo metadata"
        + (f" for {', '.join(targets)}" if targets else "")
        + "; do not edit it by hand.",
        "",
        "== Summary ==",
        "",
    ]
    missing = []
    for p in rows:
        out.append(f"{p['name']} {p['version']}  {p.get('license') or 'NO LICENCE EXPRESSION'}  {p.get('repository') or ''}".rstrip())
    out += ["", "Engine: C emitted by Bend (bendlang), including the Bend runtime. Apache-2.0.",
            "Linux engine and CLI builds link musl libc statically. MIT.", ""]
    for p in rows:
        root, files = licence_files(p)
        extra = [f for pat, fs in SUPPLEMENT if re.fullmatch(pat, p["name"]) for f in fs]
        out += ["", "=" * 78, f"{p['name']} {p['version']}", f"Licence: {p.get('license') or '(see files)'}"]
        if p.get("repository"):
            out.append(f"Source: {p['repository']}")
        if not files and not extra:
            missing.append(f"{p['name']} {p['version']}")
        for f in files:
            rel = os.path.relpath(f, root)
            out += ["", f"--- {p['name']}/{rel} ---", "", read(f).rstrip()]
        for f in extra:
            out += ["", f"--- {f} (upstream; the crate package omits it) ---", "", read(os.path.join(HERE, "notices", f)).rstrip()]
    out += ["", "=" * 78, "Bend runtime (in the emitted engine C)", "Licence: Apache-2.0", "Source: https://github.com/bendlang/bend",
            "", read(os.path.join(HERE, "notices", "bend.LICENSE")).rstrip()]
    out += ["", "=" * 78, "musl libc (static Linux builds)", "Licence: MIT", "Source: https://musl.libc.org/",
            "", read(os.path.join(HERE, "notices", "musl.COPYRIGHT")).rstrip()]
    out += ["", "=" * 78, "Standard licence texts", "", "--- MIT ---", "", MIT, "", "--- Apache-2.0 ---", "",
            "Apache License, Version 2.0: https://www.apache.org/licenses/LICENSE-2.0.txt",
            "The full text is included above with every crate that ships an Apache-2.0 LICENSE file."]
    return "\n".join(out).rstrip() + "\n", missing


