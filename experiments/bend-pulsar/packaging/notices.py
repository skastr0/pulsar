def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", action="append", default=[])
    ap.add_argument("-o", dest="out")
    ap.add_argument("--check")
    a = ap.parse_args()
    text, missing = render(metadata(a.target), a.target)
    for m in missing:
        print(f"notices: {m} ships no licence file and has no SUPPLEMENT entry", file=sys.stderr)
    if missing:
        return 1
    if a.check:
        cur = read(a.check) if os.path.isfile(a.check) else ""
        if cur != text:
            print(f"notices: {a.check} is stale; regenerate with packaging/notices.py -o {a.check}", file=sys.stderr)
            return 1
        print(f"notices: {a.check} is current")
        return 0
    if a.out:
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
