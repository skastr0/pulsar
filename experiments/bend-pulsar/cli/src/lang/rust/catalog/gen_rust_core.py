#!/usr/bin/env python3
"""Generate rust-core.toml from the std docs installed by rustup (rust-docs component).
at = page of the std docs that justifies the class, doc = its first sentence (or, for the panic
class, the first sentence of the method's "Panics" section). Edit this generator, not the TOML."""
import glob, html, os, re, sys

D = glob.glob(os.path.expanduser("~/.rustup/toolchains/stable-*/share/doc/rust/html/std/"))[0]
VER = "1.98.1"


def text(s):
    s = re.sub(r"<[^>]+>", "", s)
    return html.unescape(re.sub(r"\s+", " ", s)).strip()


def first_sentence(s):
    return s.split(". ")[0].rstrip(".") + "."


def docblock(seg):
    m = re.search(r'<div class="docblock">(.*?)</div>', seg, re.S)
    return first_sentence(text(m.group(1))) if m else None


def item_doc(page):
    return docblock(open(D + page, errors="replace").read())


def method_doc(page, name, panics=False):
    t = open(D + page, errors="replace").read()
    i = t.find('id="method.%s"' % name)
    seg = t[i : i + 8000]
    if panics:
        h = re.search(r'id="panics[-0-9]*"', seg)
        m = re.search(r"<p>(.*?)</p>", seg[h.end():], re.S) if h else None
        return first_sentence(text(m.group(1))) if m else None
    return docblock(seg)


# (sym, class, via, at page, doc)
rows = []
def add(sym, cls, page, doc, anchor=None):
    at = "std@%s:%s%s" % (VER, page, "#" + anchor if anchor else "")
    rows.append((sym, cls, at, doc))

for fn in ["read_to_string", "read", "write", "read_dir", "create_dir_all", "remove_file", "copy", "rename"]:
    add("std#fs::" + fn, "blocking", "fs/fn.%s.html" % fn, item_doc("fs/fn.%s.html" % fn))
for m in ["open", "create"]:
    add("std#fs::File::" + m, "blocking", "fs/struct.File.html", method_doc("fs/struct.File.html", m), "method." + m)
add("std#thread::sleep", "blocking", "thread/fn.sleep.html", item_doc("thread/fn.sleep.html"))
add("std#net::TcpStream::connect", "blocking", "net/struct.TcpStream.html", method_doc("net/struct.TcpStream.html", "connect"), "method.connect")
for mac in ["println", "print", "eprintln", "eprint", "dbg"]:
    add("std#%s!" % mac, "log", "macro.%s.html" % mac, item_doc("macro.%s.html" % mac))
for mac in ["panic", "todo", "unimplemented", "unreachable"]:
    add("std#%s!" % mac, "exception-style", "macro.%s.html" % mac, item_doc("macro.%s.html" % mac))
for m, page in [("unwrap", "result/enum.Result.html"), ("expect", "result/enum.Result.html"), ("unwrap_err", "result/enum.Result.html"), ("expect_err", "result/enum.Result.html")]:
    add("syntax#method." + m, "exception-style", page, method_doc(page, m, panics=True), "method." + m)
add("syntax#let-underscore", "error-erasing", "result/enum.Result.html", item_doc("result/enum.Result.html"))
add("syntax#ok-discarded", "error-erasing", "result/enum.Result.html", method_doc("result/enum.Result.html", "ok"), "method.ok")

rows.sort(key=lambda r: r[0])
q = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = []
out.append("# Rust-lane catalog: classes of the Rust standard library and of the panic and discarded-result syntax. Always on for Rust; class data and rules.")
out.append("# Generated by gen_rust_core.py from the rust-docs std pages (at = page, doc = its first sentence, or for panic the first sentence of the method's Panics section).")
out.append("# `syntax#method.<name>` entries match a method call by its name only (no receiver type); their CS rows carry ctx bit 64.")
out.append('format = "pulsar-catalog 0"')
out.append('id = "rust-core"')
out.append('scope = "lane"')
out.append('sources = ["rust-docs %s (std)"]' % VER)
out.append("")
out.append("classes = [")
for c in [("blocking", 2), ("log", 3), ("error-erasing", 4), ("exception-style", 15)]:
    out.append('  { class = %s, id = %d, rule = %s },' % (q(c[0]), c[1], q("rust-core/" + c[0])))
out.append("]")
out.append("")
out.append("symbols = [")
for sym, cls, at, doc in rows:
    out.append("  { sym = %s, class = %s, ver = %s, at = %s, doc = %s }," % (q(sym), q(cls), q("std"), q(at), q(doc)))
out.append("]")
out.append("")
out.append("rules = [")
rules = [
    ("rust.blocking-in-async", "blocking", 1, 4, "makes a blocking std call inside an async function or block, which stalls the executor thread instead of yielding"),
    ("rust.discarded-result", "error-erasing", 0, 4, "throws a result away with `let _ =` or a dropped `.ok()`, so a failure goes unseen"),
    ("rust.panic-outside-tests", "exception-style", 0, 4, "can panic in production code: unwrap, expect, panic!, todo!, unimplemented! or unreachable! where the failure should travel as a value"),
]
for rid, cls, any_, none, says in rules:
    page = {"blocking": "thread/fn.sleep.html", "error-erasing": "result/enum.Result.html", "exception-style": "macro.panic.html"}[cls]
    doc = {"blocking": item_doc("thread/fn.sleep.html"), "error-erasing": item_doc("result/enum.Result.html"), "exception-style": item_doc("macro.panic.html")}[cls]
    out.append("  { id = %s, class = %s, ctx_any = %d, ctx_none = %d, says = %s, ver = %s, at = %s, doc = %s }," % (q(rid), q(cls), any_, none, q(says), q("std"), q("std@%s:%s" % (VER, page)), q(doc)))
out.append("]")
sys.stdout.write("\n".join(out) + "\n")
